// Regenerates packages/api-client/src/types.ts from the ts-rs output directory.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const dir = join(root, 'packages/api-client/src/generated');
const names = readdirSync(dir)
  .filter((f) => f.endsWith('.ts'))
  .map((f) => f.slice(0, -3))
  .sort();
const lines = names.map((n) => `export type { ${n} } from './generated/${n}.ts';`);
writeFileSync(
  join(root, 'packages/api-client/src/types.ts'),
  `// Generated by tools/scripts/gen-api-types.mjs — do not edit.\n${lines.join('\n')}\n`,
);
console.log(`wrote ${names.length} type exports`);
